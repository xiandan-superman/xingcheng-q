'use strict'
// The accepted R2/R3 shapes, vivid R4 palettes and cream A are the only artwork sources.
// Runtime packages contain compact native data; none depend on browser preview code.
const fs = require('node:fs'), path = require('node:path'), vm = require('node:vm')
const root = path.resolve(__dirname, '..'), previews = path.resolve(root, '../../..', 'previews')
const manifest = require('../config/avatar-system.json')
const context = vm.createContext({})
for (const file of ['星橙Q-形状扩展-R2-20261105/shapes.js', '星橙Q-形状家族-R3-20261105/family.js', '星橙Q-固定配色-R4-20261105/palette.js', '星橙Q-奶油白适配-R5-20261105/cream.js']) {
  vm.runInContext(fs.readFileSync(path.join(previews, file), 'utf8'), context, {filename:file})
}
const accepted = context.QCreamStudy, palettes = accepted.P.palettes
if (manifest.shapes.length !== 11 || new Set(manifest.shapes.map(s => s.id)).size !== 11 || palettes.length !== 13 || accepted.selection.id !== 'ink-gold' || accepted.selection.status !== 'user-confirmed') throw Error('Avatar approval source is incomplete')
const rules = manifest.shapes.filter(s => s.reward).map(s => ({shape:s.id, ...s.reward, enabled:true}))
const metadata = {
  version:manifest.version, defaultShape:manifest.defaultShape, legacyShapeAliases:manifest.legacyShapeAliases,
  shapes:manifest.shapes.map(({id,name}) => ({id,name})),
  colors:palettes.map(({id,name,group}) => ({id,name,group})), rules
}
const artwork = {...metadata, shapes:manifest.shapes.map(({id,name,studyID}) => {
  const s = accepted.Q.shapes.find(s => s.id === studyID)
  if (!s) throw Error('Missing accepted shape: ' + id)
  const body = s.id === 'base' ? 'M126 0A126 126 0 1 0 -126 0A126 126 0 1 0 126 0Z' : 'M' + s.start.join(' ') + 'C' + s.curves.map(c => c.join(' ')).join(' ') + 'Z'
  return {id,name,body,face:s.face,star:s.star}
}), colors:palettes.map(p => ({id:p.id,name:p.name,group:p.group,hex:p.ramp[2],ramp:p.ramp,shade:p.shade,eyes:p.id === 'creme' ? accepted.profile('ink-gold').eyes : '#FFF8EE',star:p.id === 'creme' ? accepted.profile('ink-gold').star : '#FFF3CE'}))}
const json = data => JSON.stringify(data, null, 2) + '\n'
const outputs = {
  'miniapp/utils/avatar-colors.js':fs.readFileSync(path.join(root,'config/avatar-colors.js'),'utf8'),
  'cloudfunctions/student/avatar-colors.js':fs.readFileSync(path.join(root,'config/avatar-colors.js'),'utf8'),
  'cloudfunctions/admin/avatar-colors.js':fs.readFileSync(path.join(root,'config/avatar-colors.js'),'utf8'),
  'miniapp/utils/avatar-catalog.js': '// Generated by scripts/build-avatar-system.cjs from the approved artwork.\nmodule.exports = ' + JSON.stringify(artwork) + '\n',
  'cloudfunctions/student/avatar-catalog.json':json(metadata),
  'cloudfunctions/admin/avatar-catalog.json':json(metadata),
  'admin-web/src/avatar-catalog.js':'// Generated avatar/reward contract; do not edit separately.\nexport const avatarCatalog = ' + JSON.stringify(metadata) + '\n'
}
let stale = false
for (const [name, content] of Object.entries(outputs)) {
  const file = path.join(root, name)
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content) { console.error('Stale avatar catalog: ' + name); stale = true }
  } else { fs.mkdirSync(path.dirname(file), {recursive:true}); fs.writeFileSync(file, content) }
}
if (stale) process.exitCode = 1
else console.log((process.argv.includes('--check') ? 'Verified' : 'Generated') + ': 11 shapes, 13 palettes, 10 rewards; cream A.')
